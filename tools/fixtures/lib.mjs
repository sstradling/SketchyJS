/** Upstream path for one imported reference file. `catalog.json` is produced by the importer. */
export function upstreamSourcePath(path) {
  if (path === "UPSTREAM-LICENSE") return "LICENSE";
  if (path.startsWith("assets/")) return `Tests/SketchyTests/Fixtures/${path.slice("assets/".length)}`;
  if (path === "images/catalog.json") return "generated by tools/fixtures/import-assets.mjs from docs/images";
  if (path.startsWith("images/")) return `docs/images/${path.slice("images/".length)}`;
  return null;
}

/**
 * Reference images accepted for Phase 0 without rerunning DocsGalleryRenderer.
 * Hashes come from the manifest file entries so they cannot drift from disk.
 */
export function acceptedReferences(files) {
  return [
    {
      id: "reference-image-regeneration",
      status: "accepted: upstream copies",
      source: {
        repo: upstream.repo,
        tag: upstream.tag,
        commit: upstream.commit,
        paths: ["docs/images", "Tests/SketchyTests/Fixtures", "LICENSE"],
      },
      followUp: "Regeneration via DocsGalleryRenderer is deferred until pixel parity work.",
      files: files
        .filter((file) => file.fidelity === "upstream-copy")
        .map((file) => ({ path: file.path, sourcePath: upstreamSourcePath(file.path), sha256: file.sha256, bytes: file.bytes })),
    },
  ];
}

